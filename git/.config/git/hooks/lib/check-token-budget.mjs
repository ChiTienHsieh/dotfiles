#!/usr/bin/env node

// Block staged files that are too large for an agent to read in one go.
// Tokens are estimated as bytes / 4. Files no one writes by hand (lockfiles,
// codegen, minified bundles, binaries) are skipped.

import { execFileSync } from "node:child_process";
import {
  git,
  isIgnored,
  loadIgnoreRules,
  mergeParentRefs,
  parseIgnoreRules,
  readIfExists,
  unchangedFromAnyParent,
} from "./staged-files.mjs";
import path from "node:path";

const DEFAULT_MAX_TOKENS = 5000;
const BYTES_PER_TOKEN = 4;
const POLICY_FILE = ".token-budget-policy";
const IGNORE_FILE = ".token-budget-ignore";

// Not written by people or agents: regenerated by tools, so splitting them
// by hand is impossible or pointless.
const DEFAULT_IGNORE = parseIgnoreRules(`
package-lock.json
npm-shrinkwrap.json
pnpm-lock.yaml
yarn.lock
bun.lock
bun.lockb
deno.lock
Cargo.lock
Gemfile.lock
composer.lock
poetry.lock
Pipfile.lock
uv.lock
pdm.lock
go.sum
flake.lock
*.min.js
*.min.css
*.map
*.snap
*.svg
*_pb2.py
*_pb2.pyi
*.pb.go
*.generated.*
*.gen.*
generated/
__generated__/
dist/
build/
vendor/
node_modules/
`);

// Common markers codegen tools put in a file's header.
const GENERATED_MARKER =
  /@generated|do not edit|auto-?generated|automatically generated/i;

function parsePolicy(repoRoot) {
  const policy = { enabled: true, maxTokens: DEFAULT_MAX_TOKENS };
  const text = readIfExists(path.join(repoRoot, POLICY_FILE));
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^([A-Za-z][A-Za-z0-9_-]*)\s*[:=]\s*(.+)$/);
    if (!match) continue;
    const key = match[1].toLowerCase();
    const value = match[2].trim().replace(/^["']|["']$/g, "");
    if (key === "enabled") {
      policy.enabled = !["false", "0", "no", "off"].includes(value.toLowerCase());
    }
    if (key === "maxtokens" || key === "max_tokens") {
      const maxTokens = Number.parseInt(value, 10);
      if (Number.isFinite(maxTokens) && maxTokens > 0) {
        policy.maxTokens = maxTokens;
      }
    }
  }
  return policy;
}

// Staged regular files with their blob ids. `--raw -z` keeps odd paths
// intact and exposes the mode, so symlinks and submodules are skipped.
function stagedBlobs() {
  const out = git([
    "diff", "--cached", "--raw", "-z", "--no-abbrev", "--no-renames",
    "--diff-filter=ACM",
  ]);
  const fields = out.split("\0");
  const blobs = [];
  for (let i = 0; i + 1 < fields.length; i += 2) {
    const [, newMode, , newOid] = fields[i].split(" ");
    const file = fields[i + 1];
    if (newMode === "100644" || newMode === "100755") {
      blobs.push({ file, oid: newOid });
    }
  }
  return blobs;
}

function blobSizes(oids) {
  if (oids.length === 0) return [];
  const out = execFileSync("git", ["cat-file", "--batch-check=%(objectsize)"], {
    input: `${oids.join("\n")}\n`,
    encoding: "utf8",
  });
  return out.trim().split("\n").map(Number);
}

function blobContent(oid) {
  return execFileSync("git", ["cat-file", "blob", oid], { maxBuffer: 1 << 30 });
}

// Files marked `linguist-generated` in .gitattributes are codegen too.
function markedGenerated(files) {
  if (files.length === 0) return new Set();
  const out = execFileSync(
    "git",
    ["check-attr", "-z", "--cached", "--stdin", "linguist-generated"],
    { input: `${files.join("\0")}\0`, encoding: "utf8" },
  );
  const fields = out.split("\0");
  const generated = new Set();
  for (let i = 0; i + 2 < fields.length; i += 3) {
    if (["set", "true"].includes(fields[i + 2])) generated.add(fields[i]);
  }
  return generated;
}

function looksGenerated(content) {
  // Same heuristic git uses for binary: a NUL byte near the start.
  const head = content.subarray(0, 8000);
  if (head.includes(0)) return true;
  const firstLines = head.toString("utf8").split("\n").slice(0, 5).join("\n");
  return GENERATED_MARKER.test(firstLines);
}

function printFailures(failures, maxTokens) {
  const maxBytes = maxTokens * BYTES_PER_TOKEN;
  console.error("");
  console.error(`❌ 檔案太大：每個檔最多 ${maxTokens} tokens（tokens = bytes / 4，約 ${maxBytes} bytes）`);
  console.error("");
  for (const { file, tokens } of failures) {
    const parts = Math.ceil(tokens / maxTokens);
    console.error(`  - ${file}: 約 ${tokens} tokens，至少要拆成 ${parts} 個檔`);
  }
  console.error(`
大檔案讓 agent 每次都得整份讀進來，又貴又容易看漏。請把上面的檔案拆小，
每個新檔都低於 ${maxTokens} tokens，再重新 git add 和 commit：

  1. 先找出邊界：一個檔只做一件事。列出檔案裡的區塊（函式、class、元件、
     測試群組、文件章節），把彼此獨立的區塊分組。
  2. 每組搬到一個新檔，檔名說清楚它在做什麼（例如 utils.js 拆成
     date-format.js、price-calc.js），放在原檔旁邊或同名資料夾裡。
  3. 依檔案種類處理原檔：
     - 程式：原檔改成從新檔 import／re-export，呼叫端不用跟著改。
     - 測試：照被測的功能拆成多個測試檔，共用的 fixture 和 helper 放進
       獨立的 helper 檔。
     - 文件（Markdown 等）：照章節拆，原檔留目錄和指向各章節檔的連結。
     - 單頁 HTML：CSS 搬進 .css、script 搬進 .js（再依功能拆成多個模組），
       HTML 用 <link> 和 <script type="module"> 載入。
     - 資料或設定：拆成多個檔，由一個入口檔合併載入。
  4. 只搬家，不改行為。拆完跑一次測試，確認結果跟拆之前一樣。

不要用刪註解、壓縮、把多行擠成一行之類的方式硬塞進上限。

如果這個檔不是人或 agent 寫的（lockfile、codegen 產生的檔），把它的路徑加進
repo 根目錄的 ${IGNORE_FILE}（寫法同 .gitignore）。整個 repo 要調整上限或關掉，
在 ${POLICY_FILE} 寫 maxTokens=<數字> 或 enabled=false。
`);
}

function main() {
  const repoRoot = git(["rev-parse", "--show-toplevel"]).trim();
  const policy = parsePolicy(repoRoot);
  if (!policy.enabled) return;

  const repoIgnore = loadIgnoreRules(repoRoot, IGNORE_FILE);
  let blobs = stagedBlobs().filter(
    ({ file }) => !isIgnored(file, DEFAULT_IGNORE) && !isIgnored(file, repoIgnore),
  );

  const maxBytes = policy.maxTokens * BYTES_PER_TOKEN;
  const sizes = blobSizes(blobs.map(({ oid }) => oid));
  blobs = blobs
    .map((blob, i) => ({ ...blob, bytes: sizes[i] }))
    .filter(({ bytes }) => bytes > maxBytes);
  if (blobs.length === 0) return;

  const mergeParents = mergeParentRefs();
  if (mergeParents.length > 0) {
    blobs = blobs.filter(({ file }) => !unchangedFromAnyParent(file, mergeParents));
  }

  const generated = markedGenerated(blobs.map(({ file }) => file));
  const failures = blobs
    .filter(({ file, oid }) => !generated.has(file) && !looksGenerated(blobContent(oid)))
    .map(({ file, bytes }) => ({ file, tokens: Math.ceil(bytes / BYTES_PER_TOKEN) }));

  if (failures.length === 0) return;
  printFailures(failures, policy.maxTokens);
  process.exit(1);
}

main();
