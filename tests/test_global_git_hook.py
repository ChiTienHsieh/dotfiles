"""Run the actual global dispatcher and Markdown checker in temporary repos."""
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
HOOK = ROOT / "git/.config/git/hooks/pre-commit"
CHECKER = HOOK.parent / "lib/check-md-zh-tw-ratio.mjs"
TOKEN_CHECKER = HOOK.parent / "lib/check-token-budget.mjs"


class GlobalGitHookTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.repo = Path(self.temp.name) / "repo"
        self.repo.mkdir()
        self.env = dict(os.environ, HOME=self.temp.name, GIT_CONFIG_NOSYSTEM="1",
                        GIT_CONFIG_GLOBAL=os.devnull)
        self.git("init", "-q")
        self.git("config", "user.name", "Fixture")
        self.git("config", "user.email", "fixture@example.invalid")
        self.git("commit", "--allow-empty", "-qm", "seed")

    def git(self, *args):
        return subprocess.run(["git", *args], cwd=self.repo, env=self.env,
                              capture_output=True, text=True, check=True)

    def test_common_hook_runs_in_main_and_linked_worktree(self):
        linked = Path(self.temp.name) / "linked"
        self.git("worktree", "add", "--detach", str(linked))
        local_hook = self.repo / ".git/hooks/pre-commit"
        local_hook.write_text("#!/bin/sh\necho repository-hook\nexit 9\n")
        local_hook.chmod(0o755)
        for cwd in (self.repo, linked):
            result = subprocess.run(["sh", str(HOOK)], cwd=cwd, env=self.env,
                                    capture_output=True, text=True)
            self.assertEqual(result.returncode, 9, result.stdout + result.stderr)
            self.assertIn("repository-hook", result.stdout)

    def test_markdown_names_are_not_quoted_trimmed_or_split(self):
        for name in ("說明.md", " leading space.md", "two\nlines.md"):
            with self.subTest(name=name):
                path = self.repo / name
                path.write_text("Unsupported terminology repeated throughout this otherwise entirely English document. " * 4)
                self.git("add", "--", name)
                result = subprocess.run(["node", str(CHECKER)], cwd=self.repo, env=self.env,
                                        capture_output=True, text=True)
                self.assertNotEqual(result.returncode, 0, "Markdown filename escaped the checker")
                self.git("restore", "--staged", "--", name)
                path.unlink()


class TokenBudgetTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.repo = Path(self.temp.name)
        self.env = dict(os.environ, HOME=self.temp.name, GIT_CONFIG_NOSYSTEM="1",
                        GIT_CONFIG_GLOBAL=os.devnull)
        self.git("init", "-q")

    def git(self, *args):
        return subprocess.run(["git", *args], cwd=self.repo, env=self.env,
                              capture_output=True, text=True, check=True)

    def stage(self, name, content):
        path = self.repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_text(content)
        self.git("add", "--", name)

    def check(self):
        return subprocess.run(["node", str(TOKEN_CHECKER)], cwd=self.repo, env=self.env,
                              capture_output=True, text=True)

    BIG = "const x = 1;\n" * 1600  # ~20.8 KB, over 5,000 tokens

    def test_blocks_oversized_file_with_split_instructions(self):
        self.stage("src/app.js", self.BIG)
        result = self.check()
        self.assertEqual(result.returncode, 1)
        self.assertIn("src/app.js", result.stderr)
        self.assertIn("拆", result.stderr)

    def test_allows_file_at_the_limit(self):
        self.stage("src/app.js", "x" * 20000)
        self.assertEqual(self.check().returncode, 0)

    def test_skips_files_no_one_writes_by_hand(self):
        cases = {
            "web/package-lock.json": self.BIG,
            "dist/bundle.js": self.BIG,
            "lib/app.min.js": self.BIG,
            "api/schema.ts": "// @generated by openapi\n" + self.BIG,
            "img/photo.png": b"\x89PNG\x00" + b"\x01" * 30000,
        }
        for name, content in cases.items():
            self.stage(name, content)
        result = self.check()
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_repo_rules_and_policy(self):
        self.stage(".gitattributes", "proto/** linguist-generated\n")
        self.stage("proto/api.ts", self.BIG)
        self.stage(".token-budget-ignore", "tracker/index.html\n")
        self.stage("tracker/index.html", self.BIG)
        self.assertEqual(self.check().returncode, 0)
        self.stage("notes.md", "x" * 4500)
        self.stage(".token-budget-policy", "maxTokens=1000\n")
        self.assertEqual(self.check().returncode, 1)
        self.stage(".token-budget-policy", "enabled=false\n")
        self.assertEqual(self.check().returncode, 0)

    def test_odd_file_names_are_checked(self):
        self.stage("two\nlines 說明.txt", self.BIG)
        result = self.check()
        self.assertEqual(result.returncode, 1)
        self.assertIn("說明", result.stderr)


if __name__ == "__main__":
    unittest.main()
